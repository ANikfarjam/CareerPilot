"use client"

import { useEffect, useState } from "react"
import {
  Bot,
  Briefcase,
  ChevronRight,
  CircleCheck,
  CircleX,
  File,
  FileImage,
  FileText,
  Files,
  Folder,
  FolderGit2,
  FolderOpen,
  FolderPlus,
  GraduationCap,
  Library,
  LoaderCircle,
  RefreshCw,
  ScrollText,
  Sparkles,
  TriangleAlert,
  Trophy,
} from "lucide-react"

import { Markdown } from "@/components/markdown"
import { StatTile } from "@/components/stat-tile"
import { StatusPill } from "@/components/status-pill"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import { Checkbox } from "@/components/ui/checkbox"
import { Collapsible, CollapsibleContent, CollapsibleTrigger } from "@/components/ui/collapsible"
import {
  ApiError,
  createUserDocsFolders,
  getKnowledgeRun,
  getUserDocs,
  listKnowledgeRuns,
  startKnowledgeRun,
  type DocFolder,
  type DocKind,
  type DocNode,
  type KnowledgeRun,
  type PortalChanges,
  type UserDocs,
} from "@/lib/api"
import { cn } from "@/lib/utils"

const POLL_MS = 3000

const KIND_ICONS: Record<DocKind, React.ComponentType<{ className?: string }>> = {
  resumes: Briefcase,
  education: GraduationCap,
  projects: FolderGit2,
  papers: ScrollText,
  achievements: Trophy,
  other: Files,
}

// Docs/user_docs as the knowledge base agent expects it (agents/knowledge_base/agent.py FOLDERS).
const LAYOUT = `Docs/user_docs/
├── workexperience/        resumes (.pdf / .md)
├── education/             transcripts, diplomas, certificates
├── projects/
│   ├── <project-name>/    one folder per project
│   │   ├── <write-up>.md  or .pdf; images next to it are ignored
│   │   └── media/
│   └── …
├── papers/                published papers (.pdf / .md)
├── achievements/          hackathons, competitions, awards
├── <anything>.md          other notes (bio, LinkedIn export, …)
└── user_knowledge.md      generated by the agent, don't edit by hand`

export default function KnowledgePage() {
  const [docs, setDocs] = useState<UserDocs | null>(null)
  const [selected, setSelected] = useState<DocKind[]>([])
  const [updatePortals, setUpdatePortals] = useState(true)
  const [run, setRun] = useState<KnowledgeRun | null>(null)
  const [starting, setStarting] = useState(false)
  const [refreshing, setRefreshing] = useState(false)
  const [guideOpen, setGuideOpen] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const isRunning = starting || run?.status === "queued" || run?.status === "running"
  const folders = docs?.folders ?? []
  const totalDocuments = folders.reduce((sum, f) => sum + f.documents, 0)
  const firstTime = docs !== null && totalDocuments === 0
  const missingFolders = folders.filter((f) => !f.exists)
  // Checked kinds whose folder has nothing to read yet.
  const emptySelected = folders.filter((f) => selected.includes(f.kind) && f.documents === 0)
  const canGenerate = !isRunning && selected.length > 0 && emptySelected.length === 0

  // Re-scans Docs/user_docs.
  const loadDocs = () =>
    getUserDocs()
      .then(setDocs)
      .catch((e) => setError(errorMessage(e)))

  const handleRefresh = () => {
    setRefreshing(true)
    loadDocs().finally(() => setRefreshing(false))
  }

  // First load: preselect the kinds that have documents, and open the setup guide for a new user.
  useEffect(() => {
    getUserDocs()
      .then((next) => {
        setDocs(next)
        const provided = next.folders.filter((f) => f.documents > 0).map((f) => f.kind)
        setSelected(provided)
        setGuideOpen(provided.length === 0)
      })
      .catch((e) => setError(errorMessage(e)))
    listKnowledgeRuns()
      .then((runs) => setRun(runs[0] ?? null))
      .catch(() => {})
  }, [])

  // Poll the run until it finishes, then reload the folders and the new knowledge base.
  const runId = run?.id
  const runActive = run?.status === "queued" || run?.status === "running"
  useEffect(() => {
    if (!runId || !runActive) return
    let stopped = false
    const timer = setInterval(async () => {
      try {
        const next = await getKnowledgeRun(runId)
        if (stopped) return
        setRun(next)
        if (next.status === "succeeded") loadDocs()
      } catch (e) {
        if (stopped) return
        if (e instanceof ApiError && e.status === 404) setRun(null) // the API restarted; runs live in its memory
        else setError(errorMessage(e))
      }
    }, POLL_MS)
    return () => {
      stopped = true
      clearInterval(timer)
    }
  }, [runId, runActive])

  const handleGenerate = async () => {
    setStarting(true)
    setError(null)
    try {
      setRun(await startKnowledgeRun({ kinds: selected, update_portals: updatePortals }))
    } catch (e) {
      setError(
        e instanceof ApiError && e.status === 409
          ? "Another agent run is in progress. Try again when it finishes."
          : errorMessage(e),
      )
    } finally {
      setStarting(false)
    }
  }

  const handleCreateFolders = async () => {
    setError(null)
    try {
      setDocs(await createUserDocsFolders())
    } catch (e) {
      setError(errorMessage(e))
    }
  }

  const toggleKind = (kind: DocKind) =>
    setSelected((kinds) => (kinds.includes(kind) ? kinds.filter((k) => k !== kind) : [...kinds, kind]))

  return (
    <div className="relative flex min-h-full flex-1 flex-col">
      {/* Brand glow */}
      <div className="pointer-events-none absolute inset-x-0 top-0 -z-10 h-[480px] bg-[radial-gradient(60%_60%_at_20%_0%,color-mix(in_oklch,var(--brand-blue)_30%,transparent),transparent),radial-gradient(50%_50%_at_85%_10%,color-mix(in_oklch,var(--brand-green)_18%,transparent),transparent)]" />

      <main className="mx-auto flex w-full max-w-7xl flex-1 flex-col gap-6 px-4 py-8 sm:px-6 sm:py-10">
        <div className="flex justify-end">
          <StatusPill running={isRunning} />
        </div>

        {/* Hero */}
        <section className="rounded-2xl border bg-card/60 p-6 shadow-xl shadow-black/20 backdrop-blur sm:p-8">
          <div className="flex flex-col gap-6 md:flex-row md:items-end md:justify-between">
            <div className="space-y-3">
              <span className="inline-flex items-center gap-1.5 rounded-full border border-brand-teal/30 bg-brand-teal/10 px-3 py-1 text-xs font-medium text-brand-teal">
                <Sparkles className="size-3.5" />
                Knowledge base
              </span>
              <h1 className="text-3xl font-semibold tracking-tight sm:text-4xl">
                Teach the agents{" "}
                <span className="bg-linear-to-r from-brand-teal to-brand-green bg-clip-text text-transparent">
                  about you
                </span>
              </h1>
              <p className="max-w-xl text-sm leading-relaxed text-muted-foreground sm:text-base">
                Drop your resumes, projects, papers and achievements into{" "}
                <code className="rounded bg-muted px-1 py-0.5 font-mono text-[0.85em]">Docs/user_docs</code>. The agent
                compiles them into one knowledge base that the search, scoring and resume agents read, and tunes
                your job search to it.
              </p>
            </div>
            <Button
              size="lg"
              onClick={handleGenerate}
              disabled={!canGenerate}
              className="h-12 rounded-xl bg-linear-to-r from-brand-blue via-brand-teal to-brand-green px-6 text-base font-semibold text-brand-navy shadow-lg shadow-brand-teal/25 transition hover:shadow-brand-teal/40 hover:brightness-110"
            >
              {isRunning ? <LoaderCircle className="size-5 animate-spin" /> : <Sparkles className="size-5" />}
              {isRunning ? "Generating…" : docs?.knowledge ? "Update knowledge base" : "Generate knowledge base"}
            </Button>
          </div>

          {error && <p className="mt-4 text-sm text-destructive">{error}</p>}
          {!isRunning && selected.length === 0 && docs && (
            <p className="mt-4 text-sm text-muted-foreground">Tick at least one kind of document below.</p>
          )}
          {!isRunning && emptySelected.length > 0 && (
            <p className="mt-4 flex items-center gap-1.5 text-sm text-amber-400">
              <TriangleAlert className="size-4" />
              Nothing to read yet in: {emptySelected.map((f) => f.label).join(", ")}. Add files there, then refresh,
              or untick them.
            </p>
          )}
        </section>

        {/* Stats */}
        <section className="grid gap-4 sm:grid-cols-3">
          <StatTile icon={Files} label="Documents found" value={docs ? totalDocuments : "—"} />
          <StatTile
            icon={Folder}
            label="Kinds provided"
            value={docs ? `${folders.filter((f) => f.documents > 0).length}/${folders.length}` : "—"}
          />
          <StatTile
            icon={Library}
            label="Knowledge base"
            value={docs?.knowledge_updated_at ? formatDate(docs.knowledge_updated_at) : "Not yet"}
            hint={docs?.knowledge_updated_at ? "last compiled" : undefined}
          />
        </section>

        {/* Setup guide: open for a new user, collapsed once there are documents */}
        {docs && (
          <Collapsible open={guideOpen} onOpenChange={setGuideOpen} className="rounded-2xl border bg-card p-5">
            <CollapsibleTrigger className="flex w-full items-center gap-2 text-left font-medium">
              <ChevronRight className={cn("size-4 text-muted-foreground transition", guideOpen && "rotate-90")} />
              How to organize <code className="font-mono text-sm">Docs/user_docs</code>
              {firstTime && <Badge className="bg-brand-teal/10 text-brand-teal">Start here</Badge>}
            </CollapsibleTrigger>
            <CollapsibleContent>
              <div className="mt-4 grid gap-6 lg:grid-cols-[1fr_1fr]">
                <pre className="overflow-x-auto rounded-xl border bg-muted/40 p-4 font-mono text-xs leading-relaxed">
                  {LAYOUT}
                </pre>
                <ol className="list-decimal space-y-2 pl-5 text-sm leading-relaxed text-muted-foreground">
                  <li>
                    Put your files in the folders on the left, under{" "}
                    <code className="break-all font-mono text-xs text-foreground">{docs.root}</code>. The agent reads{" "}
                    <strong className="text-foreground">.pdf</strong>, <strong className="text-foreground">.md</strong>{" "}
                    and <strong className="text-foreground">.txt</strong>; images and other files are listed but
                    ignored.
                  </li>
                  <li>Only the resumes are essential. Skip any folder you have nothing for.</li>
                  <li>
                    Tick what you are providing below, press <em>Refresh</em> to check the folders, then generate.
                  </li>
                  <li>
                    Added a project or a new resume later? Drop it in and press <em>Update</em>. The agent keeps the
                    facts already in the knowledge base and merges the new ones; the previous version is saved as{" "}
                    <code className="font-mono text-xs text-foreground">user_knowledge.prev.md</code>.
                  </li>
                </ol>
              </div>
              {missingFolders.length > 0 && (
                <div className="mt-4 flex flex-wrap items-center gap-3 rounded-xl border border-dashed p-3 text-sm">
                  <span className="text-muted-foreground">
                    Missing folders: {missingFolders.filter((f) => f.folder).map((f) => `${f.folder}/`).join(", ")}
                  </span>
                  <Button variant="outline" size="sm" onClick={handleCreateFolders}>
                    <FolderPlus />
                    Create them
                  </Button>
                </div>
              )}
            </CollapsibleContent>
          </Collapsible>
        )}

        <div className="grid gap-6 lg:grid-cols-[1fr_340px]">
          {/* What the user provides, and what's there */}
          <section className="min-w-0 rounded-2xl border bg-card p-5">
            <div className="mb-4 flex items-center justify-between gap-3">
              <div>
                <h2 className="font-medium">{firstTime ? "What are you providing?" : "Your documents"}</h2>
                <p className="text-xs text-muted-foreground">
                  Ticked folders are read when you generate. Each one is checked for files.
                </p>
              </div>
              <Button variant="outline" size="sm" onClick={handleRefresh} disabled={refreshing}>
                <RefreshCw className={cn(refreshing && "animate-spin")} />
                Refresh
              </Button>
            </div>

            {!docs ? (
              <div className="flex justify-center py-10">
                <LoaderCircle className="size-6 animate-spin text-brand-teal" />
              </div>
            ) : (
              <ul className="space-y-3">
                {folders.map((folder) => (
                  <FolderRow
                    key={folder.kind}
                    folder={folder}
                    checked={selected.includes(folder.kind)}
                    onToggle={() => toggleKind(folder.kind)}
                    disabled={isRunning}
                  />
                ))}
              </ul>
            )}

            <label className="mt-5 flex cursor-pointer items-start gap-3 border-t pt-4 text-sm">
              <Checkbox
                checked={updatePortals}
                onCheckedChange={setUpdatePortals}
                disabled={isRunning}
                className="mt-0.5 data-checked:border-brand-teal data-checked:bg-brand-teal dark:data-checked:bg-brand-teal"
              />
              <span>
                <span className="font-medium">Also tune the job search</span>
                <span className="block text-xs text-muted-foreground">
                  Lets the agent adjust portals.yml: the title keywords to look for and to skip, and which companies
                  to add or drop.
                </span>
              </span>
            </label>
          </section>

          {/* Agent activity */}
          <section className="h-fit rounded-2xl border bg-card p-5">
            <h2 className="mb-5 flex items-center gap-2 font-medium">
              <Bot className="size-4 text-brand-teal" />
              Agent activity
            </h2>
            <RunPanel run={run} isRunning={isRunning} />
          </section>
        </div>

        {/* Current knowledge base */}
        {docs?.knowledge && (
          <section className="rounded-2xl border bg-card p-6 sm:p-8">
            <div className="mb-4 flex flex-wrap items-center justify-between gap-2">
              <h2 className="flex items-center gap-2 font-medium">
                <Library className="size-4 text-brand-teal" />
                user_knowledge.md
              </h2>
              {docs.knowledge_updated_at && (
                <span className="text-xs text-muted-foreground">Updated {formatDateTime(docs.knowledge_updated_at)}</span>
              )}
            </div>
            <div className="max-h-[640px] overflow-y-auto pr-2 text-sm leading-relaxed">
              <Markdown variant="document">{docs.knowledge}</Markdown>
            </div>
          </section>
        )}
      </main>
    </div>
  )
}

// One document kind: checkbox, where it goes, whether its folder has files, and a tree of them.
function FolderRow({
  folder,
  checked,
  onToggle,
  disabled,
}: {
  folder: DocFolder
  checked: boolean
  onToggle: () => void
  disabled: boolean
}) {
  const Icon = KIND_ICONS[folder.kind]
  const path = folder.folder ? `Docs/user_docs/${folder.folder}/` : "Docs/user_docs/"
  return (
    <li
      className={cn(
        "rounded-xl border p-4 transition",
        checked ? "border-brand-teal/30 bg-brand-teal/5" : "opacity-80",
      )}
    >
      <label className="flex cursor-pointer items-start gap-3">
        <Checkbox
          checked={checked}
          onCheckedChange={onToggle}
          disabled={disabled}
          className="mt-0.5 data-checked:border-brand-teal data-checked:bg-brand-teal dark:data-checked:bg-brand-teal"
        />
        <Icon className="mt-0.5 size-4 shrink-0 text-brand-teal" />
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
            <span className="font-medium">{folder.label}</span>
            <code className="font-mono text-xs text-muted-foreground">{path}</code>
            <FolderStatus folder={folder} checked={checked} />
          </div>
          <p className="mt-0.5 text-xs text-muted-foreground">{folder.description}</p>
        </div>
      </label>
      {folder.tree.length > 0 && (
        <ul className="mt-3 ml-7 border-l pl-3">
          {folder.tree.map((node) => (
            <TreeNode key={node.path} node={node} />
          ))}
        </ul>
      )}
    </li>
  )
}

function FolderStatus({ folder, checked }: { folder: DocFolder; checked: boolean }) {
  if (folder.documents > 0) {
    return (
      <Badge className="bg-brand-green/10 text-brand-green">
        <CircleCheck />
        {folder.documents} {folder.documents === 1 ? "document" : "documents"}
      </Badge>
    )
  }
  const label = folder.exists ? "Empty" : "Folder missing"
  return (
    <Badge variant="secondary" className={cn(checked ? "bg-amber-400/10 text-amber-400" : "text-muted-foreground")}>
      {checked && <TriangleAlert />}
      {label}
    </Badge>
  )
}

// A file or folder of the tree; folders open by default unless they hold nothing the agent reads (media/).
function TreeNode({ node }: { node: DocNode }) {
  const [open, setOpen] = useState(() => hasUsable(node))
  if (!node.is_dir) {
    const FileIcon = node.usable ? FileText : /\.(png|jpe?g|gif|webp|svg)$/i.test(node.name) ? FileImage : File
    return (
      <li className={cn("flex items-center gap-1.5 py-0.5 text-sm", !node.usable && "text-muted-foreground/60")}>
        <FileIcon className={cn("size-3.5 shrink-0", node.usable && "text-brand-teal")} />
        <span className="truncate">{node.name}</span>
        {node.size !== null && <span className="shrink-0 text-xs text-muted-foreground">{formatSize(node.size)}</span>}
        {!node.usable && <span className="shrink-0 text-xs">· ignored</span>}
      </li>
    )
  }
  const FolderIcon = open ? FolderOpen : Folder
  return (
    <Collapsible render={<li />} open={open} onOpenChange={setOpen}>
      <CollapsibleTrigger className="flex items-center gap-1.5 py-0.5 text-sm hover:text-brand-teal">
        <ChevronRight className={cn("size-3.5 transition", open && "rotate-90")} />
        <FolderIcon className="size-3.5 text-muted-foreground" />
        {node.name}/
        <span className="text-xs text-muted-foreground">{node.children.length}</span>
      </CollapsibleTrigger>
      <CollapsibleContent render={<ul />} className="ml-1.5 border-l pl-3">
        {node.children.map((child) => (
          <TreeNode key={child.path} node={child} />
        ))}
      </CollapsibleContent>
    </Collapsible>
  )
}

function RunPanel({ run, isRunning }: { run: KnowledgeRun | null; isRunning: boolean }) {
  if (!run || (isRunning && run.status !== "queued" && run.status !== "running")) {
    return (
      <div className="flex flex-col items-center gap-3 rounded-xl border border-dashed py-10 text-center">
        {isRunning ? (
          <LoaderCircle className="size-6 animate-spin text-brand-teal" />
        ) : (
          <Bot className="size-6 text-muted-foreground" />
        )}
        <p className="max-w-52 text-sm text-muted-foreground">
          {isRunning ? "Starting the agent…" : "Generate the knowledge base to watch the agent work."}
        </p>
      </div>
    )
  }
  if (run.status === "queued" || run.status === "running") {
    return (
      <div className="space-y-3 text-sm">
        <p className="flex items-center gap-2">
          <LoaderCircle className="size-4 animate-spin text-brand-teal" />
          {run.status === "queued" ? "Queued" : "Reading your documents and writing each section"}
        </p>
        <p className="text-xs text-muted-foreground">
          From: {run.kinds.join(", ")}. This takes several minutes: one model call per section and per project
          {run.update_portals ? ", then one to tune portals.yml" : ""}.
        </p>
      </div>
    )
  }
  if (run.status === "failed") {
    return (
      <p className="flex items-start gap-2 text-sm text-destructive">
        <CircleX className="mt-0.5 size-4 shrink-0" />
        {run.error ?? "Unknown error"}
      </p>
    )
  }
  return (
    <div className="space-y-4 text-sm">
      <p className="flex items-center gap-2">
        <CircleCheck className="size-4 text-brand-green" />
        Built from {run.documents.length} documents
        {run.finished_at && <span className="text-xs text-muted-foreground">· {formatDateTime(run.finished_at)}</span>}
      </p>
      {run.portals && <PortalChangeList changes={run.portals} />}
    </div>
  )
}

function PortalChangeList({ changes }: { changes: PortalChanges }) {
  const rows: [string, string[]][] = [
    ["Keywords added", changes.positive_added],
    ["Keywords removed", changes.positive_removed],
    ["Skip keywords added", changes.negative_added],
    ["Skip keywords removed", changes.negative_removed],
    ["Companies added", changes.companies_added.map((c) => String(c.name))],
    ["Companies re-enabled", changes.companies_enabled],
    ["Companies dropped", changes.companies_disabled],
  ]
  const nonEmpty = rows.filter(([, values]) => values.length > 0)
  return (
    <div className="space-y-2 border-t pt-3">
      <p className="text-xs font-medium uppercase tracking-wider text-muted-foreground">portals.yml</p>
      {nonEmpty.length === 0 ? (
        <p className="text-muted-foreground">No changes.</p>
      ) : (
        nonEmpty.map(([label, values]) => (
          <div key={label}>
            <p className="text-xs text-muted-foreground">{label}</p>
            <p>{values.join(", ")}</p>
          </div>
        ))
      )}
      {changes.companies_added.length > 0 && (
        <p className="text-xs text-amber-400">Check the careers URLs of the added companies in portals.yml.</p>
      )}
      {changes.reasoning && <p className="text-xs text-muted-foreground">{changes.reasoning}</p>}
    </div>
  )
}

function hasUsable(node: DocNode): boolean {
  return node.usable || node.children.some(hasUsable)
}

function errorMessage(e: unknown) {
  return e instanceof Error ? e.message : String(e)
}

function formatSize(bytes: number) {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`
}

function formatDate(value: string) {
  return new Date(value).toLocaleDateString(undefined, { month: "short", day: "numeric" })
}

function formatDateTime(value: string) {
  return new Date(value).toLocaleString(undefined, { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })
}
